def apply_fixes(all_questions, topic_map):
    """all_questions — compile_all_1000 жасаған тізім (id бойынша). Түзетілген тізімді қайтарады."""
    rng = random.Random(7)
    result = []
    seen = set()
    for q in all_questions:
        qid = q["id"]
        if qid in REMOVE:
            continue
        if any(q["text"].startswith(p) for p in TEXT_REMOVE_PREFIX):
            continue

        if qid in REWRITE:
            spec = REWRITE[qid]
            opts = [spec["correct"]] + list(spec["distractors"])
            order = list(range(4))
            rng.shuffle(order)
            q = dict(q)
            q["topicId"] = spec["topicId"]
            q["topicName"] = topic_map[spec["topicId"]]
            q["text"] = spec["text"]
            q["options"] = [opts[i] for i in order]
            q["correctIndex"] = order.index(0)
            q["explanation"] = spec["explanation"]
            q["source"] = q.get("source", "") + " (түзетілген)"
        elif qid in CLEAN_OPTIONS:
            opts, ci = CLEAN_OPTIONS[qid]
            q = dict(q)
            q["options"] = list(opts)
            q["correctIndex"] = ci
            q["explanation"] = f"Дұрыс жауабы: {opts[ci]}."

        if qid in TOPIC_ONLY:
            q = dict(q)
            q["topicId"] = TOPIC_ONLY[qid]
            q["topicName"] = topic_map[TOPIC_ONLY[qid]]

        if q["text"] in CONTEXT_FIXES:
            fx = CONTEXT_FIXES[q["text"]]
            q = dict(q)
            for k, v in fx.items():
                q[k] = v

        key = q["text"].strip().lower()
        if key in seen:
            continue
        seen.add(key)
        result.append(q)
    return result
